using Grab.Api.Models;
using Microsoft.EntityFrameworkCore;

namespace Grab.Api.Data;

public class GrabDbContext(DbContextOptions<GrabDbContext> options) : DbContext(options)
{
    public DbSet<AdminAudit> AdminAudits => Set<AdminAudit>();
    public DbSet<AdminProfile> AdminProfiles => Set<AdminProfile>();
    public DbSet<AdminRole> AdminRoles => Set<AdminRole>();
    public DbSet<HomeBanner> HomeBanners => Set<HomeBanner>();
    public DbSet<PlatformSettings> PlatformSettings => Set<PlatformSettings>();
    public DbSet<User> Users => Set<User>();
    public DbSet<UserProfilePhoto> UserProfilePhotos => Set<UserProfilePhoto>();
    public DbSet<Driver> Drivers => Set<Driver>();
    public DbSet<Ride> Rides => Set<Ride>();
    public DbSet<RideMerchantResponse> RideMerchantResponses => Set<RideMerchantResponse>();
    public DbSet<Payment> Payments => Set<Payment>();
    public DbSet<Review> Reviews => Set<Review>();
    public DbSet<Merchant> Merchants => Set<Merchant>();
    public DbSet<MerchantListing> MerchantListings => Set<MerchantListing>();
    public DbSet<MerchantImage> MerchantImages => Set<MerchantImage>();
    public DbSet<MerchantOrder> MerchantOrders => Set<MerchantOrder>();
    public DbSet<MerchantOrderItem> MerchantOrderItems => Set<MerchantOrderItem>();
    public DbSet<ParcelDelivery> ParcelDeliveries => Set<ParcelDelivery>();
    public DbSet<DeliveryStop> DeliveryStops => Set<DeliveryStop>();
    public DbSet<AccountData> AccountData => Set<AccountData>();
    public DbSet<SharedStorageIdentity> SharedStorageIdentities => Set<SharedStorageIdentity>();
    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<User>().Property(x => x.IsActive).HasDefaultValue(true);
        b.Entity<User>().Property(x => x.SecurityVersion).IsConcurrencyToken();
        b.Entity<UserProfilePhoto>().HasKey(x => x.UserId);
        b.Entity<UserProfilePhoto>().HasOne<User>().WithOne(x => x.ProfilePhoto).HasForeignKey<UserProfilePhoto>(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<UserProfilePhoto>().Property(x => x.ContentType).HasMaxLength(30);
        b.Entity<AdminProfile>().HasKey(x => x.UserId);
        b.Entity<AdminProfile>().HasOne<User>().WithOne().HasForeignKey<AdminProfile>(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<AdminProfile>().Property(x => x.ContactPhone).HasMaxLength(30);
        b.Entity<AdminProfile>().Property(x => x.JobTitle).HasMaxLength(100);
        b.Entity<AdminProfile>().Property(x => x.Bio).HasMaxLength(500);
        b.Entity<AdminProfile>().Property(x => x.AvatarContentType).HasMaxLength(30);
        b.Entity<AdminProfile>().Property(x => x.Version).IsRowVersion();
        // Restrict: a role cannot be deleted while administrators are assigned to it.
        b.Entity<AdminProfile>().HasOne<AdminRole>().WithMany().HasForeignKey(x => x.AdminRoleId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<AdminRole>().Property(x => x.Name).HasMaxLength(60);
        b.Entity<AdminRole>().HasIndex(x => x.Name).IsUnique();
        b.Entity<AdminRole>().Property(x => x.Description).HasMaxLength(300);
        b.Entity<AdminRole>().Property(x => x.Permissions).HasMaxLength(1000);
        b.Entity<AdminRole>().Property(x => x.Version).IsRowVersion();
        b.Entity<PlatformSettings>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<PlatformSettings>().Property(x => x.SupportEmail).HasMaxLength(254);
        b.Entity<PlatformSettings>().Property(x => x.SupportPhone).HasMaxLength(30);
        b.Entity<PlatformSettings>().Property(x => x.SupportHours).HasMaxLength(120);
        b.Entity<PlatformSettings>().Property(x => x.OfficeAddress).HasMaxLength(300);
        b.Entity<PlatformSettings>().Property(x => x.Announcement).HasMaxLength(300);
        b.Entity<PlatformSettings>().Property(x => x.MaintenanceMessage).HasMaxLength(300);
        b.Entity<PlatformSettings>().Property(x => x.Version).IsRowVersion();
        b.Entity<AdminAudit>().Property(x => x.ActorName).HasMaxLength(120);
        b.Entity<AdminAudit>().Property(x => x.Resource).HasMaxLength(40);
        b.Entity<AdminAudit>().Property(x => x.Action).HasMaxLength(100);
        b.Entity<AdminAudit>().Property(x => x.Reason).HasMaxLength(300);
        b.Entity<AdminAudit>().HasIndex(x => x.CreatedAt);
        b.Entity<HomeBanner>().Property(x => x.Title).HasMaxLength(80);
        b.Entity<HomeBanner>().Property(x => x.Subtitle).HasMaxLength(160);
        b.Entity<HomeBanner>().Property(x => x.LinkUrl).HasMaxLength(300);
        b.Entity<HomeBanner>().Property(x => x.ContentType).HasMaxLength(30);
        b.Entity<HomeBanner>().HasIndex(x => new { x.IsActive, x.SortOrder });
        b.Entity<AccountData>().HasKey(x => x.UserId);
        b.Entity<AccountData>().HasOne<User>().WithOne().HasForeignKey<AccountData>(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<AccountData>().Property(x => x.Version).IsConcurrencyToken();
        b.Entity<SharedStorageIdentity>().Property(x => x.StorageId).HasDefaultValueSql("NEWID()");
        b.Entity<SharedStorageIdentity>().HasData(new { Id = 1 });
        b.Entity<User>().HasIndex(x => x.Email).IsUnique().HasFilter("[Email] IS NOT NULL");
        b.Entity<User>().HasIndex(x => x.PhoneNumber).IsUnique();
        b.Entity<User>().Property(x => x.Email).HasMaxLength(254);
        b.Entity<User>().Property(x => x.FullName).HasMaxLength(120);
        b.Entity<User>().Property(x => x.PhoneNumber).HasMaxLength(30);
        b.Entity<User>().Property(x => x.Role).HasConversion<string>().HasMaxLength(20);
        b.Entity<Driver>().HasIndex(x => x.UserId).IsUnique();
        b.Entity<Driver>().HasIndex(x => x.VehiclePlate).IsUnique();
        b.Entity<Driver>().Property(x => x.VehiclePlate).HasMaxLength(30);
        b.Entity<Driver>().Property(x => x.VehicleType).HasMaxLength(50);
        b.Entity<Driver>().Property(x => x.Version).IsRowVersion();
        b.Entity<Driver>().HasOne<User>().WithOne().HasForeignKey<Driver>(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Ride>().HasOne<User>().WithMany().HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Ride>().HasOne<Driver>().WithMany().HasForeignKey(x => x.DriverId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Ride>().HasOne(x => x.Merchant).WithMany().HasForeignKey(x => x.MerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Ride>().HasIndex(x => new { x.MerchantId, x.Status });
        b.Entity<RideMerchantResponse>().HasKey(x => new { x.RideId, x.MerchantId });
        b.Entity<RideMerchantResponse>().HasOne<Ride>().WithMany().HasForeignKey(x => x.RideId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<RideMerchantResponse>().HasOne<Merchant>().WithMany().HasForeignKey(x => x.MerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<RideMerchantResponse>().HasIndex(x => x.MerchantId).IsUnique().HasFilter("[IsActive] = 1");
        b.Entity<RideMerchantResponse>().HasIndex(x => x.RideId).IsUnique().HasFilter("[IsActive] = 1");
        b.Entity<RideMerchantResponse>().ToTable(t => t.HasCheckConstraint("CK_RideMerchantResponses_ActiveAccepted", "[IsActive] = 0 OR [Accepted] = 1"));
        b.Entity<Ride>().Property(x => x.Version).IsRowVersion();
        b.Entity<Ride>().Property(x => x.Fare).HasPrecision(12, 2);
        b.Entity<Ride>().Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
        b.Entity<Ride>().Property(x => x.VehicleType).HasConversion<string>().HasMaxLength(20).HasDefaultValue(RideVehicleType.Motorcycle);
        b.Entity<Ride>().Property(x => x.PickupLocation).HasMaxLength(300);
        b.Entity<Ride>().Property(x => x.Destination).HasMaxLength(300);
        b.Entity<Ride>().HasIndex(x => new { x.CustomerId, x.CreatedAt });
        b.Entity<Ride>().HasIndex(x => new { x.DriverId, x.Status });
        b.Entity<Payment>().HasOne<Ride>().WithOne().HasForeignKey<Payment>(x => x.RideId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Payment>().Property(x => x.Amount).HasPrecision(12, 2);
        b.Entity<Review>().HasOne<Ride>().WithOne().HasForeignKey<Review>(x => x.RideId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Review>().HasOne<User>().WithMany().HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Review>().HasOne<Driver>().WithMany().HasForeignKey(x => x.DriverId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Review>().Property(x => x.Comment).HasMaxLength(1000);
        b.Entity<Review>().ToTable(t => t.HasCheckConstraint("CK_Reviews_Rating", "[Rating] BETWEEN 1 AND 5"));
        b.Entity<Merchant>().HasIndex(x => x.UserId).IsUnique();
        b.Entity<Merchant>().HasOne<User>().WithOne().HasForeignKey<Merchant>(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<Merchant>().Property(x => x.Service).HasConversion<string>().HasMaxLength(20);
        b.Entity<Merchant>().Property(x => x.BusinessName).HasMaxLength(120);
        b.Entity<Merchant>().Property(x => x.OwnerName).HasMaxLength(120);
        b.Entity<Merchant>().Property(x => x.ContactPhone).HasMaxLength(30);
        b.Entity<Merchant>().Property(x => x.Email).HasMaxLength(254);
        b.Entity<Merchant>().Property(x => x.Address).HasMaxLength(300);
        b.Entity<Merchant>().Property(x => x.City).HasMaxLength(100);
        b.Entity<Merchant>().Property(x => x.Category).HasMaxLength(100);
        b.Entity<Merchant>().Property(x => x.Description).HasMaxLength(1500);
        b.Entity<Merchant>().Property(x => x.OpeningHours).HasMaxLength(200);
        b.Entity<Merchant>().Property(x => x.MotorcycleLicensePlate).HasMaxLength(30);
        b.Entity<MerchantListing>().HasOne(x => x.Merchant).WithMany().HasForeignKey(x => x.MerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantListing>().HasOne<MerchantImage>().WithMany().HasForeignKey(x => x.ImageId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantListing>().Property(x => x.Title).HasMaxLength(120);
        b.Entity<MerchantListing>().Property(x => x.Description).HasMaxLength(1500);
        b.Entity<MerchantListing>().Property(x => x.Price).HasPrecision(12, 2);
        b.Entity<MerchantListing>().HasIndex(x => new { x.IsPublished, x.UpdatedAt });
        b.Entity<MerchantListing>().ToTable(t => t.HasCheckConstraint("CK_MerchantListings_Price", "[Price] > 0"));
        b.Entity<MerchantImage>().HasOne<Merchant>().WithMany().HasForeignKey(x => x.MerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantImage>().Property(x => x.ContentType).HasMaxLength(30);
        b.Entity<MerchantOrder>().HasOne<User>().WithMany().HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantOrder>().HasOne(x => x.Merchant).WithMany().HasForeignKey(x => x.MerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantOrder>().HasMany(x => x.Items).WithOne().HasForeignKey(x => x.OrderId).OnDelete(DeleteBehavior.Cascade);
        b.Entity<MerchantOrder>().Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
        b.Entity<MerchantOrder>().Property(x => x.PaymentMethod).HasConversion<string>().HasMaxLength(20);
        b.Entity<MerchantOrder>().Property(x => x.DeliveryAddress).HasMaxLength(300);
        b.Entity<MerchantOrder>().Property(x => x.Note).HasMaxLength(500);
        b.Entity<MerchantOrder>().Property(x => x.Subtotal).HasPrecision(12, 2);
        b.Entity<MerchantOrder>().Property(x => x.DeliveryFee).HasPrecision(12, 2);
        b.Entity<MerchantOrder>().Property(x => x.Total).HasPrecision(12, 2);
        b.Entity<MerchantOrder>().Property(x => x.Version).IsRowVersion();
        b.Entity<MerchantOrder>().HasIndex(x => new { x.CustomerId, x.CreatedAt });
        b.Entity<MerchantOrder>().HasIndex(x => new { x.MerchantId, x.Status });
        b.Entity<MerchantOrder>().ToTable(t => t.HasCheckConstraint("CK_MerchantOrders_Total", "[Subtotal] > 0 AND [DeliveryFee] >= 0 AND [Total] = [Subtotal] + [DeliveryFee]"));
        b.Entity<MerchantOrderItem>().HasOne<MerchantListing>().WithMany().HasForeignKey(x => x.ListingId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<MerchantOrderItem>().Property(x => x.Title).HasMaxLength(120);
        b.Entity<MerchantOrderItem>().Property(x => x.UnitPrice).HasPrecision(12, 2);
        b.Entity<MerchantOrderItem>().ToTable(t => t.HasCheckConstraint("CK_MerchantOrderItems_Quantity", "[Quantity] BETWEEN 1 AND 50 AND [UnitPrice] > 0"));

        b.Entity<ParcelDelivery>().HasOne<User>().WithMany().HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<ParcelDelivery>().HasOne(x => x.CourierMerchant).WithMany().HasForeignKey(x => x.CourierMerchantId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<ParcelDelivery>().HasOne<MerchantImage>().WithMany().HasForeignKey(x => x.PickupProofPhotoId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<ParcelDelivery>().HasMany(x => x.Stops).WithOne().HasForeignKey(x => x.DeliveryId).OnDelete(DeleteBehavior.Cascade);
        b.Entity<ParcelDelivery>().HasIndex(x => new { x.CustomerId, x.CreatedAt });
        b.Entity<ParcelDelivery>().HasIndex(x => new { x.Status, x.VehicleType, x.CreatedAt });
        b.Entity<ParcelDelivery>().HasIndex(x => x.CourierMerchantId).IsUnique()
            .HasFilter("[CourierMerchantId] IS NOT NULL AND [Status] IN (N'Accepted', N'PickedUp', N'InTransit')");
        b.Entity<ParcelDelivery>().Property(x => x.Version).IsRowVersion();
        b.Entity<ParcelDelivery>().Property(x => x.ServiceType).HasConversion<string>().HasMaxLength(20);
        b.Entity<ParcelDelivery>().Property(x => x.VehicleType).HasConversion<string>().HasMaxLength(20);
        b.Entity<ParcelDelivery>().Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
        b.Entity<ParcelDelivery>().Property(x => x.PaymentMethod).HasConversion<string>().HasMaxLength(20);
        b.Entity<ParcelDelivery>().Property(x => x.InsuranceTier).HasConversion<string>().HasMaxLength(20);
        b.Entity<ParcelDelivery>().Property(x => x.PickupName).HasMaxLength(120);
        b.Entity<ParcelDelivery>().Property(x => x.PickupPhone).HasMaxLength(30);
        b.Entity<ParcelDelivery>().Property(x => x.PickupAddress).HasMaxLength(300);
        b.Entity<ParcelDelivery>().Property(x => x.PricingMode).HasMaxLength(40);
        foreach (var property in new[] { nameof(ParcelDelivery.BaseFare), nameof(ParcelDelivery.DistanceFare),
            nameof(ParcelDelivery.VehicleFare), nameof(ParcelDelivery.SizeFare), nameof(ParcelDelivery.ExtraStopFare),
            nameof(ParcelDelivery.InsuranceFare), nameof(ParcelDelivery.CodFee), nameof(ParcelDelivery.TotalFare),
            nameof(ParcelDelivery.CodAmount) })
            b.Entity<ParcelDelivery>().Property<decimal>(property).HasPrecision(12, 2);
        b.Entity<ParcelDelivery>().ToTable(t => t.HasCheckConstraint("CK_ParcelDeliveries_Fare",
            "[TotalFare] = [BaseFare] + [DistanceFare] + [VehicleFare] + [SizeFare] + [ExtraStopFare] + [InsuranceFare] + [CodFee] AND [TotalFare] >= 0 AND [CodAmount] >= 0"));

        b.Entity<DeliveryStop>().HasOne<MerchantImage>().WithMany().HasForeignKey(x => x.ProofPhotoId).OnDelete(DeleteBehavior.Restrict);
        b.Entity<DeliveryStop>().HasIndex(x => new { x.DeliveryId, x.Position }).IsUnique();
        b.Entity<DeliveryStop>().Property(x => x.RecipientName).HasMaxLength(120);
        b.Entity<DeliveryStop>().Property(x => x.RecipientPhone).HasMaxLength(30);
        b.Entity<DeliveryStop>().Property(x => x.Address).HasMaxLength(300);
        b.Entity<DeliveryStop>().Property(x => x.Description).HasMaxLength(300);
        b.Entity<DeliveryStop>().Property(x => x.FailureReason).HasMaxLength(300);
        b.Entity<DeliveryStop>().Property(x => x.ParcelSize).HasConversion<string>().HasMaxLength(20);
        b.Entity<DeliveryStop>().Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
        b.Entity<DeliveryStop>().Property(x => x.WeightKg).HasPrecision(8, 2);
        b.Entity<DeliveryStop>().Property(x => x.CodAmount).HasPrecision(12, 2);
        b.Entity<DeliveryStop>().ToTable(t => t.HasCheckConstraint("CK_DeliveryStops_Values",
            "[Position] BETWEEN 1 AND 5 AND [WeightKg] > 0 AND [CodAmount] BETWEEN 0 AND 200"));
    }
}
