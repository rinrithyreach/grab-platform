function format(text: string, vars?: Vars) {
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
}

function makeAdminTranslator(lang: Lang) {
  return {
    lang,
    /** Translate English admin copy; unknown text stays in English. */
    a: (english: string, vars?: Vars) => format(lang === "km" ? km[english] ?? english : english, vars),
    /** Locale for dates and weekday names. */
    locale: lang === "km" ? "km-KH" : "en-GB",
  };
}
export type AdminTranslate = ReturnType<typeof makeAdminTranslator>["a"];

// Built once per language so `a` is a stable reference (safe in hook dependency lists).
const TRANSLATORS = { en: makeAdminTranslator("en"), km: makeAdminTranslator("km") };

export function useAdminT() {
  const { lang } = useSettings();
  return TRANSLATORS[lang] ?? TRANSLATORS.en;
}
